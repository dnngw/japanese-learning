// Writes licenses/THIRD_PARTY_LICENSES.txt: the license text of every production
// npm dependency (MIT/BSD/Apache require it to ship with the app). Runs offline.
// Usage: node tools/collect-licenses.mjs

import { execFileSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(ROOT, 'licenses', 'THIRD_PARTY_LICENSES.txt')

const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm'
const dirs = execFileSync(npm, ['ls', '--omit=dev', '--all', '--parseable'], { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
  .split('\n')
  .map((l) => l.trim())
  .filter((d) => d && d !== ROOT && existsSync(path.join(d, 'package.json')))

// Some packages don't ship a license file: use the standard text of their declared license.
const MIT = readFileSync(path.join(ROOT, 'LICENSE'), 'utf8').split('---')[0].replace(/Copyright \(c\) .*\n/, '')
function standardText(pkg) {
  const author = typeof pkg.author === 'string' ? pkg.author : pkg.author?.name
  if (pkg.license === 'MIT') return MIT.replace('MIT License\n', `MIT License\n\nCopyright (c) ${author ?? pkg.name + ' contributors'}\n`).trim()
  if (pkg.license === 'Apache-2.0') return readFileSync(path.join(ROOT, 'licenses', 'Apache-2.0.txt'), 'utf8').trim()
  return `License: ${pkg.license ?? 'unknown'} (no license file in the package)`
}

const seen = new Set()
const sections = []
for (const dir of dirs.sort()) {
  const pkg = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'))
  const id = `${pkg.name}@${pkg.version}`
  if (seen.has(id)) continue
  seen.add(id)
  const licenseFile = readdirSync(dir).find((f) => /^(licen[cs]e|copying|notice)(\.|$|-)/i.test(f))
  const text = licenseFile ? readFileSync(path.join(dir, licenseFile), 'utf8').trim() : standardText(pkg)
  sections.push(`${'='.repeat(78)}\n${id}  (${pkg.license ?? 'unknown'})\n${pkg.homepage ?? pkg.repository?.url ?? ''}\n${'='.repeat(78)}\n\n${text}\n`)
}

writeFileSync(
  OUT,
  `Third-party software included in JapanLearn\nGenerated by tools/collect-licenses.mjs. Data, fonts and audio: see THIRD_PARTY_NOTICES.md.\n\n${sections.join('\n')}`,
)
console.log(`${sections.length} packages → ${path.relative(ROOT, OUT)}`)
